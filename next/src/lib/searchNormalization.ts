/**
 * キャラ検索用の文字列正規化。
 *
 * 完全一致では拾えない入力ゆらぎを吸収して「ゆるい部分一致」を実現する:
 * - NFKC: 全角英数・半角カナなどの互換文字を統一
 * - 英字は小文字化（クリストファー等のローマ字表記ゆれ対策）
 * - カタカナ→ひらがな: 「カズマ」でも「かずま」でも reading（ひらがな）に当たる
 * - 空白・中点の除去: 「はづき けい」「クリストファー・ウェザーフィールド」対策
 *
 * タイポまで許容するファジー検索が欲しくなったら、この正規化を前段に
 * Fuse.js 等を重ねる想定（現状 61 キャラなので部分一致で十分）。
 */
export const normalizeForSearch = (s: string): string =>
  s.normalize('NFKC')
    .toLowerCase()
    // カタカナ(ァ..ヶ)をひらがなへ（コードポイント差 0x60）
    .replace(/[ァ-ヶ]/g, ch =>
      String.fromCharCode(ch.charCodeAt(0) - 0x60)
    )
    .replace(/[\s・]/g, '');
